#!/usr/bin/env node
/**
 * Refresh the market-pricing snapshot from the open "gpu-rental-prices"
 * dataset (CC BY 4.0 — https://github.com/adriannutiu/gpu-rental-prices).
 *
 * Runs at build time (npm run fetch:market). If the network fetch fails,
 * the committed snapshot is kept as-is, so builds never break offline.
 *
 * Only flagship families are kept (H100/H200/B200/B300/GB300/A100/L40S/MI300X)
 * and re-shaped into src/data/marketPricing.js — manual edits to the curated
 * file will be overwritten on the next successful refresh.
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT = path.join(root, 'src', 'data', 'marketPricing.js')
const URL = 'https://raw.githubusercontent.com/adriannutiu/gpu-rental-prices/main/data/latest.json'
const KEEP = new Set(['h100', 'h200', 'b200', 'b300', 'gb300', 'a100', 'l40s', 'mi300x'])

try {
  const res = await fetch(URL, { signal: AbortSignal.timeout(30000) })
  if (!res.ok) throw new Error(`HTTP ${res.status}`)
  const data = await res.json()
  const offers = (data.offers || []).filter(o => KEEP.has(o.gpu))
  if (offers.length < 20) throw new Error(`only ${offers.length} offers — dataset changed?`)

  const lines = offers.map(o =>
    `    ['${o.provider}', '${o.gpu}', '${o.gpu.toUpperCase()}', ${o.vram_gb}, ${o.usd_hr}, '${o.kind}', ${o.min_gpus || 1}],`
  )

  const providerMeta = Object.entries(data.providers || {})
    .map(([k, v]) => `  ${JSON.stringify(k)}: { name: ${JSON.stringify(k)}, url: ${JSON.stringify(v.source_url || '')} },`)
    .join('\n')

  const js = `/**
 * AUTO-GENERATED by scripts/fetch-market-data.mjs — do not edit by hand.
 * Source: ${data ? 'gpu-rental-prices (CC BY 4.0) · gpurentalprices.com' : ''}
 * https://github.com/adriannutiu/gpu-rental-prices
 * Snapshot date: ${data.date || new Date().toISOString().slice(0, 10)}
 */

export const MARKET_DATA = {
  asOf: ${JSON.stringify(data.date || new Date().toISOString().slice(0, 10))},
  source: {
    name: 'gpu-rental-prices (CC BY 4.0)',
    repo: 'https://github.com/adriannutiu/gpu-rental-prices',
    live: 'https://gpurentalprices.com',
    providersTracked: ${data.meta?.provider_count || 0},
  },
  offers: [
${lines.join('\n')}
  ],
}

export const PROVIDER_META = {
${providerMeta}
}

const FAMILY_OF = {
  h100: ['h100'],
  h200: ['h200'],
  b200: ['b200', 'b300', 'gb300'],
  a100: ['a100'],
  l40s: ['l40s'],
  mi300x: ['mi300x'],
}

export function offersForFamily(family) {
  const ids = FAMILY_OF[family] || []
  return MARKET_DATA.offers
    .map(([provider, gpu, variant, vram, usd, kind, minGpus]) => ({ provider, gpu, variant, vram, usd, kind, minGpus }))
    .filter(o => ids.includes(o.gpu))
}

export function marketSummary() {
  const groups = {}
  for (const [provider, gpu, variant, vram, usd, kind, minGpus] of MARKET_DATA.offers) {
    const fam = Object.keys(FAMILY_OF).find(f => FAMILY_OF[f].includes(gpu))
    const g = (groups[fam] ||= { family: fam, vram, offers: [], firm: [], flexible: [], providers: new Set() })
    g.vram = Math.max(g.vram, vram)
    g.offers.push({ provider, usd, kind, minGpus, variant })
    if (kind === 'spot' || kind === 'serverless') g.flexible.push(usd)
    else g.firm.push(usd)
    g.providers.add(provider)
  }
  return Object.values(groups).map(g => {
    const all = g.offers.map(o => o.usd).sort((a, b) => a - b)
    const firmSorted = [...g.firm].sort((a, b) => a - b)
    return {
      family: g.family,
      vram: g.vram,
      count: g.offers.length,
      providerCount: g.providers.size,
      min: all[0],
      firmMin: firmSorted[0],
      median: all[Math.floor(all.length / 2)],
      cheapest: g.offers.find(o => o.usd === all[0]),
    }
  })
}
`
  fs.writeFileSync(OUT, js)
  console.log(`✅ marketPricing.js refreshed: ${offers.length} offers, ${Object.keys(data.providers || {}).length} providers, as of ${data.date}`)
} catch (err) {
  console.warn(`⚠️  market-data refresh skipped (${err.message}) — using committed snapshot`)
}
